"""Writes the IPC JSON Schema that ``json2ts`` turns into ``apps/desktop/src/ipc/generated.ts``.

From the repo root:
    uv run --project core python -m ace_core.ipc.export_schema apps/desktop/src/ipc/ipc.schema.json
    pnpm --filter ace-desktop gen:ipc
CI runs this module with ``--check`` and fails when the committed schema is stale.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any, Final, Literal

from pydantic import BaseModel
from pydantic.json_schema import GenerateJsonSchema, models_json_schema

from ace_core.ipc.events import EVENT_PAYLOADS
from ace_core.ipc.methods import METHODS
from ace_core.ipc.schemas import (
    AuthMessage,
    ErrorMessage,
    EventMessage,
    RequestMessage,
    ResponseMessage,
)

Mode = Literal["validation", "serialization"]
_REF_TEMPLATE: Final = "#/$defs/{model}"
_INCOMING: Final[list[type[BaseModel]]] = [AuthMessage, RequestMessage]
_OUTGOING: Final[list[type[BaseModel]]] = [ResponseMessage, ErrorMessage, EventMessage]


class _NoFieldTitles(GenerateJsonSchema):
    """Models keep their titles; fields get none, or json2ts emits a stray alias per field."""

    def field_title_should_be_set(self, schema: object) -> bool:
        return False


def _unique(models: Sequence[type[BaseModel]]) -> list[type[BaseModel]]:
    return list(dict.fromkeys(models))


def build_schema() -> dict[str, Any]:
    """One schema: incoming / outgoing message unions plus typed method and event maps."""
    inputs = _unique([*_INCOMING, *(spec.params for spec in METHODS.values())])
    outputs = _unique(
        [*_OUTGOING, *(spec.result for spec in METHODS.values()), *EVENT_PAYLOADS.values()]
    )
    entries: list[tuple[type[BaseModel], Mode]] = [(m, "validation") for m in inputs]
    entries += [(m, "serialization") for m in outputs]
    refs, top = models_json_schema(
        entries, ref_template=_REF_TEMPLATE, schema_generator=_NoFieldTitles
    )

    def ref(model: type[BaseModel], mode: Mode) -> dict[str, Any]:
        return {"$ref": refs[(model, mode)]["$ref"]}

    methods = {
        name: {
            "type": "object",
            "properties": {
                "params": ref(spec.params, "validation"),
                "result": ref(spec.result, "serialization"),
            },
            "required": ["params", "result"],
            "additionalProperties": False,
        }
        for name, spec in METHODS.items()
    }
    events = {name: ref(model, "serialization") for name, model in EVENT_PAYLOADS.items()}
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "AceIpc",
        "description": "ACE IPC protocol. Generated by ace_core.ipc.export_schema - do not edit.",
        "type": "object",
        "properties": {
            "incoming": {"oneOf": [ref(m, "validation") for m in _INCOMING]},
            "outgoing": {"oneOf": [ref(m, "serialization") for m in _OUTGOING]},
            "methods": {
                "type": "object",
                "properties": methods,
                "required": list(methods),
                "additionalProperties": False,
            },
            "events": {
                "type": "object",
                "properties": events,
                "required": list(events),
                "additionalProperties": False,
            },
        },
        "required": ["incoming", "outgoing", "methods", "events"],
        "additionalProperties": False,
        "$defs": top.get("$defs", {}),
    }


def render() -> str:
    return json.dumps(build_schema(), indent=2, ensure_ascii=False) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Export the IPC JSON Schema.")
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != text:
            print(f"{args.output} is out of date - regenerate it (see module docstring).")
            return 1
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
